-- =====================================================================
-- Preventivatore Wildix (TC Sistem) — schema del database
-- Si installa DENTRO un progetto Supabase già esistente senza toccarne nulla:
--   * tutte le tabelle e funzioni hanno il prefisso wx_
--   * nessun trigger su auth.users, nessuna modifica alle impostazioni di Auth
--   * entra solo chi è nella tabella wx_utenti (gli altri utenti del progetto,
--     es. i tecnici dei rapportini, non vedono nulla)
-- Da eseguire: Supabase > SQL Editor > New query > incolla > Run.
-- Si può rieseguire senza perdere dati.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Utenti abilitati (per email)
-- ---------------------------------------------------------------------
create table if not exists public.wx_utenti (
  email      text primary key check (email = lower(email)),
  nome       text not null default '',
  attivo     boolean not null default true,
  user_id    uuid unique references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create or replace function public.wx_is_utente()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.wx_utenti
    where attivo and email = lower(coalesce(auth.jwt()->>'email', ''))
  );
$$;

create or replace function public.wx_registra_accesso()
returns boolean language plpgsql security definer set search_path = public as $$
begin
  if not public.wx_is_utente() then return false; end if;
  update public.wx_utenti set user_id = auth.uid()
   where email = lower(auth.jwt()->>'email') and (user_id is distinct from auth.uid());
  return true;
end $$;

-- ---------------------------------------------------------------------
-- Clienti
