create table if not exists public.wx_clienti (
  id         uuid primary key default gen_random_uuid(),
  rs         text not null,
  ind        text not null default '',
  cap        text not null default '',
  citta      text not null default '',
  prov       text not null default '',
  piva       text not null default '',
  email      text not null default '',
  pec        text not null default '',
  sdi        text not null default '',
  ref        text not null default '',
  tel        text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists wx_clienti_rs_idx on public.wx_clienti (lower(rs));

-- ---------------------------------------------------------------------
-- Listini: Wildix CAPEX / OPEX / CLASSOUND + articoli propri (PERSONALE)
--   prezzo_gold = costo a me (prezzo Gold partner)
--   prezzo_eu   = prezzo di listino al cliente finale (End User)
--   fascia      = scaglione quantità (es. 1-5, 51+) o prefisso per i DID
--   periodo     = '' una tantum, '1m' mensile, '1y' annuale, '5y' 5 anni
-- ---------------------------------------------------------------------
create table if not exists public.wx_listino (
  id          bigint generated by default as identity primary key,
  versione    text not null,                 -- es. 'Novembre 2026' (per i PERSONALE: 'Miei')
  listino     text not null check (listino in ('CAPEX','OPEX','CLASSOUND','PERSONALE')),
  categoria   text not null default '',
  codice      text not null,
  descrizione text not null default '',
  fascia      text not null default '',
  q_min       int,
  q_max       int,
  periodo     text not null default '' check (periodo in ('','1m','1y','5y')),
  prezzo_gold numeric(14,4) not null default 0,
  prezzo_eu   numeric(14,4) not null default 0,
  ppm_gold    numeric(14,4),
  ppm_eu      numeric(14,4),
  created_at  timestamptz not null default now(),
  unique (versione, listino, codice, fascia)
);
create index if not exists wx_listino_ver_idx on public.wx_listino (versione, listino);
-- materiali propri: marca e unità di misura
alter table public.wx_listino add column if not exists marca text not null default '';
alter table public.wx_listino add column if not exists um    text not null default '';

-- ---------------------------------------------------------------------
-- Offerte
-- ---------------------------------------------------------------------
create table if not exists public.wx_offerte (
  id              uuid primary key default gen_random_uuid(),
  numero          text not null unique,          -- es. W2026/001
  data            date not null default current_date,
  stato           text not null default 'Bozza' check (stato in ('Richiesta','Bozza','Inviata','Accettata','Persa')),
  cliente_id      uuid references public.wx_clienti(id) on delete set null,
  cliente         text not null default '',
  cliente_blocco  text not null default '',
  attenzione      text not null default '',
  redatto         text not null default '',
  oggetto         text not null default '',
  versione_listino text not null default '',
  parametri       jsonb not null default '{}'::jsonb,
  righe           jsonb not null default '[]'::jsonb,   -- righe cliente (listino o libere)
  costi           jsonb not null default '[]'::jsonb,   -- costi interni non fatturati ("costi a me")
  condizioni      jsonb not null default '{}'::jsonb,
  tot_una_tantum  numeric(14,2) not null default 0,
  tot_mensile     numeric(14,2) not null default 0,
  tot_annuale     numeric(14,2) not null default 0,
  valore_anno1    numeric(14,2) not null default 0,
  costo_anno1     numeric(14,2) not null default 0,
  margine_anno1   numeric(14,2) not null default 0,
  created_by      uuid default auth.uid() references public.wx_utenti(user_id) on delete set null,
  updated_by      uuid default auth.uid() references public.wx_utenti(user_id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists wx_offerte_updated_idx on public.wx_offerte (updated_at desc);
-- stato "Richiesta" (offerte create dal bot dei venditori) anche sui database già installati
alter table public.wx_offerte drop constraint if exists wx_offerte_stato_check;
alter table public.wx_offerte add constraint wx_offerte_stato_check check (stato in ('Richiesta','Bozza','Inviata','Accettata','Persa'));

-- ---------------------------------------------------------------------
-- Impostazioni (una riga): intestazione, sconti/ricarichi predefiniti, testi
-- ---------------------------------------------------------------------
create table if not exists public.wx_impostazioni (
  id         int primary key default 1 check (id = 1),
  dati       jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid()
);
insert into public.wx_impostazioni (id) values (1) on conflict (id) do nothing;

-- ---------------------------------------------------------------------
-- updated_at / updated_by automatici
-- ---------------------------------------------------------------------
create or replace function public.wx_tocca()
returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
create or replace function public.wx_tocca_autore()
returns trigger language plpgsql as $$
begin new.updated_at := now(); new.updated_by := coalesce(auth.uid(), new.updated_by); return new; end $$;

drop trigger if exists wx_trg_clienti on public.wx_clienti;
create trigger wx_trg_clienti before update on public.wx_clienti for each row execute function public.wx_tocca();
drop trigger if exists wx_trg_offerte on public.wx_offerte;
create trigger wx_trg_offerte before update on public.wx_offerte for each row execute function public.wx_tocca_autore();
drop trigger if exists wx_trg_impostazioni on public.wx_impostazioni;
create trigger wx_trg_impostazioni before update on public.wx_impostazioni for each row execute function public.wx_tocca_autore();

-- prossimo numero offerta dell'anno (es. P004-26): ricomincia da P001 ogni anno
create or replace function public.wx_prossimo_numero(anno int default extract(year from current_date)::int)
returns text language sql stable as $$
  select 'P' || lpad((coalesce(max(substring(numero from '^P([0-9]+)-')::int), 0) + 1)::text, 3, '0') || '-' || right(anno::text, 2)
  from public.wx_offerte
  where numero ~ ('^P[0-9]+-' || right(anno::text, 2) || '$');
$$;

-- elenco versioni di listino presenti con numero righe
create or replace function public.wx_versioni_listino()
returns table (versione text, listino text, righe bigint) language sql stable security definer set search_path = public as $$
  select versione, listino, count(*) from public.wx_listino
  where public.wx_is_utente()
  group by versione, listino order by max(created_at) desc, listino;
$$;

-- ---------------------------------------------------------------------
-- Sicurezza (RLS): solo gli utenti abilitati in wx_utenti
-- ---------------------------------------------------------------------
alter table public.wx_utenti       enable row level security;
alter table public.wx_clienti      enable row level security;
alter table public.wx_listino      enable row level security;
alter table public.wx_offerte      enable row level security;
alter table public.wx_impostazioni enable row level security;

drop policy if exists wx_utenti_lettura on public.wx_utenti;
create policy wx_utenti_lettura on public.wx_utenti for select to authenticated using (public.wx_is_utente());
drop policy if exists wx_utenti_proprio on public.wx_utenti;
create policy wx_utenti_proprio on public.wx_utenti for update to authenticated
  using (public.wx_is_utente() and user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists wx_clienti_tutto on public.wx_clienti;
create policy wx_clienti_tutto on public.wx_clienti for all to authenticated
  using (public.wx_is_utente()) with check (public.wx_is_utente());
drop policy if exists wx_listino_tutto on public.wx_listino;
create policy wx_listino_tutto on public.wx_listino for all to authenticated
  using (public.wx_is_utente()) with check (public.wx_is_utente());
drop policy if exists wx_offerte_tutto on public.wx_offerte;
create policy wx_offerte_tutto on public.wx_offerte for all to authenticated
  using (public.wx_is_utente()) with check (public.wx_is_utente());
drop policy if exists wx_impostazioni_tutto on public.wx_impostazioni;
create policy wx_impostazioni_tutto on public.wx_impostazioni for all to authenticated
  using (public.wx_is_utente()) with check (public.wx_is_utente());

revoke all on public.wx_utenti, public.wx_clienti, public.wx_listino, public.wx_offerte, public.wx_impostazioni from anon, authenticated;
grant select on public.wx_utenti to authenticated;
grant update (nome) on public.wx_utenti to authenticated;
grant select, insert, update, delete on public.wx_clienti, public.wx_listino, public.wx_offerte to authenticated;
grant select, update on public.wx_impostazioni to authenticated;

revoke execute on function public.wx_is_utente(), public.wx_registra_accesso(), public.wx_prossimo_numero(int),
  public.wx_versioni_listino() from public, anon;
grant execute on function public.wx_is_utente(), public.wx_registra_accesso(), public.wx_prossimo_numero(int),
  public.wx_versioni_listino() to authenticated;

